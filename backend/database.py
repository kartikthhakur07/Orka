def seed_database():
    """Seed default team, project, and sprint telemetry data."""
    db: Session = SessionLocal()
    try:
        # Create tables if not exist
        Base.metadata.create_all(bind=engine)

        # Only seed if database is empty to prevent data loss on restarts
        existing_member = db.query(TeamMember).first()
        if existing_member:
            print("[ORKA] Database already populated with telemetry data. Skipping seed.")
            return

        print("[ORKA] Seeding database with initial team telemetry data...")

        # Seed team members
        members = []
        for m in TEAM_SEED:
            member = TeamMember(**m)
            db.add(member)
            members.append(member)
        db.flush()

        # Seed projects
        for p in PROJECTS_SEED:
            project = Project(**p)
            db.add(project)

        # Seed tasks
        for t in TASKS_SEED:
            t_copy = dict(t)
            t_copy["created_at"] = datetime.now()
            task = Task(**t_copy)
            db.add(task)

        # Seed sprint
        sprint = Sprint(**SPRINT_SEED)
        db.add(sprint)

        # Seed work DNA
        for dna in WORK_DNA_SEED:
            work_dna = WorkDNA(**dna)
            db.add(work_dna)

        db.commit()
        print("[ORKA] Database seeded successfully with IBM HR Analytics Dataset!")

    except Exception as e:
        db.rollback()
        print(f"[ORKA] Seed error: {e}")
        raise
    finally:
        db.close()